/**
 * 产物注释守卫（构建产物里不得残留源码注释 / 中文注释 / 内部编号）
 * @description 覆盖 `apps/desktop/out/main/index.js`、`out/preload/index.js` 与
 *              `out/renderer/**\/*.{js,css}`。背景（T734）：`main` / `preload` 两段原先
 *              没有 `build` 配置 ⇒ electron-vite 默认不压缩、保留注释 ⇒ 打进 asar 的
 *              产物里能直接读到源码注释（含内部编号 R5/R13/T654 与测试文件名）。
 *              配置侧修复见 `apps/desktop/electron.vite.config.ts`；配置形状的静态断言见
 *              `apps/desktop/__tests__/dist-comments-config.test.ts`（进 `vp test`）。
 *              本脚本是**产物侧**判据：直接读构建出来的东西，把「注释回流」变成可拦的失败。
 *
 * 判据（命中任一即 exit 1）：
 *  1. **行注释** `//…` 或 **块注释** `/*…*\/`（字符串外）。
 *     放行三类非泄漏注释：
 *       - `/* @__PURE__ *\/`、`/*#__PURE__*\/`（打包器纯函数标注）
 *       - `/* empty css *\/`（Vite 纯 CSS chunk 占位）
 *       - `/** generated by https://github.com/voderl/font-slice *\/`（第三方字体切片工具 banner，
 *         来自 `apps/web/public/fonts/**` 原样拷入，无中文、无内部编号、无源码上下文）
 *  2. **含中文的注释**（CJK 字符出现在注释文本内）—— 计数并入上一条的违规清单，单独标注。
 *  3. **注释内含内部编号**：`R<数字>`、`T<三位数字>`、`DEF-<数字>`、`C-<数字>`、`AC<数字>`。
 *     ⚠️ **只在注释文本内匹配** —— 产物里的合法标识符/变量名（如 `T654` 之外的普通名字、
 *     数值常量）不参与匹配，避免误杀；这也是"编号泄漏"的真实载体（注释）。
 *     注释外出现 `R5|R13|T654|R-10` 时只作 **INFO** 打印（不失败），因为那是代码语义问题、
 *     不属本守卫的「注释泄漏」范畴。
 *
 * 空转防守：
 *  - `apps/desktop/out` 不存在（未构建）⇒ **exit 0** + 一行提示（未构建不算失败）。
 *  - `out` 存在但一个 `js|css` 产物都没扫到 ⇒ **exit 1**（防守卫空转）。
 *
 * 用途：`pnpm guard:dist-comments`（已接进 `desktop:build`，构建成功后自动跑）；
 *      需要产物，故不进 CI `check` job（只 JSON/静态检查，不构建桌面端）。
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import process from 'node:process'

const OUT_ROOT = join('apps', 'desktop', 'out')
const ENTRY_FILES = [join('main', 'index.js'), join('preload', 'index.js')]
const RENDERER_EXT = /\.(js|css)$/

/** 放行的非泄漏注释（整条注释文本匹配） */
const ALLOWED_COMMENTS = [
    /^\/\*[@#]?__PURE__\*\/$/,
    // Vite 的纯 CSS chunk 占位符会补空格对齐：`/* empty css` + 空格 + `*/`
    /^\/\* empty css\s*\*\/$/,
    /^\/\*\*? generated by https:\/\/github\.com\/voderl\/font-slice \*\/$/,
    // iconfont 产物公共头（`apps/web/public/fonts/iconfont/iconfont.css` 原样拷入）
    /^\/\* Project id \d+ \*\/$/
]
/** 注释文本内的内部编号（R5 / R13 / T654 / DEF-160 / C-58 / AC13 …） */
const INTERNAL_ID = /\b(?:R\d{1,3}|T\d{3}|DEF-\d+|C-\d+|AC\d+)\b/g
/** 整份文件内的内部编号（仅 INFO，不参与判定） */
const INTERNAL_ID_ANY = /\b(?:R5|R13|T654|R-10)\b/g
const CJK = /[\u4e00-\u9fa5]/

/**
 * 字符串外的注释提取（引号感知 + 表达式位置的正则字面量跳过）
 * @description 局限性（已知、可接受）：模板串 `${…}` 插值内部按字符串内容处理 ⇒ 插值里的
 *              注释不会被找出；正则字面量里的 `\/` 因紧跟在反斜杠之后，**不当作注释开头**。
 *              正则字面量只在「前一个非空白字符是表达式起始符」（`= ( , : [ ! & | ? { } ; >`）时
 *              整体跳过：该位置上的 `/` **不可能是除号**，故不会盖掉真实注释；其它位置的正则
 *              （如 `if (x) /re/`）仍按不能识别的旧限制处理。
 *              背景（T784）：`vue@3.5.46` 的 `normalizeStyle` 多了一条字符类内置引号的组合正则
 *              `/"(?:…)"|…|\/\*[^]*?\*\//g`，旧解析在字符类的 `"` 处字符串状态失同步
 *              ⇒ 把后面的 `startsWith("/*")` 误判成块注释（构建假红）。
 *              CSS 无行注释语义（`url(http://…)` 会误报）⇒ 只在 JS 里识别 `//`。
 * @returns {{ type: 'line'|'block', line: number, text: string }[]}
 */
function extractComments(source, { lineComments = true } = {}) {
    const comments = []
    const length = source.length
    let index = 0
    let line = 1

    /** 跳过引号串（含转义）；未闭合时在行尾终止（防御性） */
    const skipQuoted = (quote) => {
        index += 1
        while (index < length) {
            const char = source[index]
            if (char === '\\') {
                if (source[index + 1] === '\n') line += 1
                index += 2
                continue
            }
            if (char === '\n') {
                line += 1
                index += 1
                // 单/双引号串不跨行；反引号（模板串）允许跨行
                if (quote !== '`') return
                continue
            }
            index += 1
            if (char === quote) return
        }
    }

    /** 正则字面量的合法前导字符（`/` 紧跟它们时只可能是正则开头，不可能是除号） */
    const REGEX_LEAD_CHARS = new Set(['=', '(', ',', ':', '[', '!', '&', '|', '?', '{', '}', ';', '>'])

    /** 跳过正则字面量本体（含字符类内的 `/` 与转义）；未闭合 / 跨行 ⇒ 不消费并返回 false */
    const skipRegex = () => {
        if (source[index - 1] === '\\') return false
        let before = index - 1
        while (before >= 0 && /\s/.test(source[before])) before -= 1
        if (before >= 0 && !REGEX_LEAD_CHARS.has(source[before])) return false
        let cursor = index + 1
        let inClass = false
        while (cursor < length) {
            const char = source[cursor]
            if (char === '\\') {
                cursor += 2
                continue
            }
            if (char === '\n') return false
            if (char === '[') inClass = true
            else if (char === ']') inClass = false
            else if (char === '/' && !inClass) {
                index = cursor + 1
                return true
            }
            cursor += 1
        }
        return false
    }

    while (index < length) {
        const char = source[index]
        if (char === '\n') {
            line += 1
            index += 1
            continue
        }
        if (char === "'" || char === '"' || char === '`') {
            skipQuoted(char)
            continue
        }
        if (char === '/' && source[index + 1] !== '/' && source[index + 1] !== '*' && skipRegex()) {
            continue
        }
        if (lineComments && char === '/' && source[index + 1] === '/' && source[index - 1] !== '\\') {
            const start = index
            while (index < length && source[index] !== '\n') index += 1
            comments.push({ type: 'line', line, text: source.slice(start, index) })
            continue
        }
        if (char === '/' && source[index + 1] === '*') {
            const start = index
            const startLine = line
            index += 2
            while (index < length && !(source[index] === '*' && source[index + 1] === '/')) {
                if (source[index] === '\n') line += 1
                index += 1
            }
            index = Math.min(index + 2, length)
            comments.push({ type: 'block', line: startLine, text: source.slice(start, index) })
            continue
        }
        index += 1
    }
    return comments
}

/** 递归列出 renderer 下的 js/css 产物 */
function listRendererArtifacts(dir) {
    const files = []
    for (const entry of readdirSync(dir)) {
        const path = join(dir, entry)
        if (statSync(path).isDirectory()) files.push(...listRendererArtifacts(path))
        else if (RENDERER_EXT.test(entry)) files.push(path)
    }
    return files
}

const outExists = statSync(OUT_ROOT, { throwIfNoEntry: false })?.isDirectory() ?? false
if (!outExists) {
    console.log(
        `[guard:dist-comments] SKIP - 未找到 ${OUT_ROOT}（桌面端未构建；未构建不算失败）`
    )
    process.exit(0)
}

const targets = ENTRY_FILES.map((rel) => join(OUT_ROOT, rel)).filter(
    (path) => statSync(path, { throwIfNoEntry: false })?.isFile() ?? false
)
const rendererDir = join(OUT_ROOT, 'renderer')
if (statSync(rendererDir, { throwIfNoEntry: false })?.isDirectory() ?? false) {
    targets.push(...listRendererArtifacts(rendererDir))
}

if (targets.length === 0) {
    console.error(
        `[guard:dist-comments] ${OUT_ROOT} 存在但未扫到任何 js|css 产物（守卫会空转，拒绝）`
    )
    process.exit(1)
}

let commentCount = 0
const violations = []
const infoIds = []

for (const file of targets) {
    const source = readFileSync(file, 'utf8')
    const isCss = file.endsWith('.css')
    for (const comment of extractComments(source, { lineComments: !isCss })) {
        commentCount += 1
        if (ALLOWED_COMMENTS.some((pattern) => pattern.test(comment.text))) continue
        const ids = comment.text.match(INTERNAL_ID) ?? []
        const hasCjk = CJK.test(comment.text)
        const reasons = [
            comment.type === 'line' ? '行注释' : '块注释',
            ...(hasCjk ? ['中文'] : []),
            ...(ids.length > 0 ? [`内部编号 ${[...new Set(ids)].join(',')}`] : [])
        ]
        violations.push(
            `${relative(OUT_ROOT, file).split(sep).join('/')}:${comment.line} [${reasons.join(' / ')}] ` +
                comment.text.replace(/\s+/g, ' ').slice(0, 100)
        )
    }
    for (const id of source.match(INTERNAL_ID_ANY) ?? []) infoIds.push(`${relative(OUT_ROOT, file)}: ${id}`)
}

if (violations.length > 0) {
    console.error('[guard:dist-comments] 产物里仍有源码注释（会被打进 asar）：')
    violations.slice(0, 40).forEach((line) => console.error('  - ' + line))
    if (violations.length > 40) console.error(`  … 另有 ${violations.length - 40} 条未列出`)
    process.exit(1)
}

if (infoIds.length > 0) {
    console.log(
        `[guard:dist-comments] INFO - 注释外出现内部编号 ${infoIds.length} 处（不判失败）：` +
            infoIds.slice(0, 5).join('; ')
    )
}
console.log(
    `[guard:dist-comments] OK - 扫描 ${targets.length} 个产物，注释 ${commentCount} 条` +
        `（全部为打包器标注/第三方 banner），无中文注释、无内部编号`
)
